begin;

create table if not exists public.oficio_destinatarios_frecuentes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  nombre_normalizado text generated always as (lower(regexp_replace(trim(nombre), '\s+', ' ', 'g'))) stored,
  veces_usado integer not null default 1,
  ultima_vez timestamptz not null default now(),
  constraint oficio_destinatarios_frecuentes_nombre_check check (length(trim(nombre)) >= 2),
  constraint oficio_destinatarios_frecuentes_nombre_unique unique (nombre_normalizado)
);

alter table public.oficio_destinatarios_frecuentes enable row level security;

drop policy if exists oficio_destinatarios_frecuentes_select_authenticated
  on public.oficio_destinatarios_frecuentes;
create policy oficio_destinatarios_frecuentes_select_authenticated
  on public.oficio_destinatarios_frecuentes for select to authenticated
  using (true);

create or replace function public.registrar_destinatario_oficio(p_nombre text)
returns void
language plpgsql
security definer
set search_path to ''
as $destinatario$
declare
  v_nombre text := nullif(regexp_replace(trim(p_nombre), '\s+', ' ', 'g'), '');
begin
  if auth.uid() is null or v_nombre is null or length(v_nombre) < 2 then
    raise exception 'Destinatario inválido';
  end if;

  insert into public.oficio_destinatarios_frecuentes (nombre, veces_usado, ultima_vez)
  values (v_nombre, 1, now())
  on conflict (nombre_normalizado)
  do update set
    veces_usado = public.oficio_destinatarios_frecuentes.veces_usado + 1,
    ultima_vez = now();
end;
$destinatario$;

revoke all on function public.registrar_destinatario_oficio(text) from public, anon;
grant execute on function public.registrar_destinatario_oficio(text) to authenticated;

commit;

notify pgrst, 'reload schema';
