-- Catálogo editable de áreas, jefes (responsables) y subáreas.
-- Reemplaza los nombres que estaban escritos en src/constants/index.ts.
--
-- Cómo usarlo: pegar todo este archivo en Supabase > SQL Editor y pulsar Run.
-- Es seguro ejecutarlo más de una vez: no duplica ni pisa datos existentes.
--
-- Modelo: una sola tabla.
--   subarea IS NULL      -> fila de un área principal; "responsable" es el jefe del área.
--   subarea IS NOT NULL  -> fila de una subárea; "responsable" es la persona que recibe la copia.
begin;

create table if not exists public.areas_responsables (
  id bigint generated by default as identity primary key,
  area text not null,
  subarea text,
  responsable text not null,
  actualizado_en timestamptz not null default now(),
  actualizado_por uuid,
  constraint areas_responsables_area_check
    check (length(trim(area)) between 2 and 120),
  constraint areas_responsables_subarea_check
    check (subarea is null or length(trim(subarea)) between 2 and 120),
  constraint areas_responsables_responsable_check
    check (length(trim(responsable)) between 2 and 160)
);

-- No se permiten dos áreas (ni dos subáreas dentro de la misma área) con el mismo nombre,
-- sin importar mayúsculas ni espacios sobrantes.
create unique index if not exists areas_responsables_nombre_unico
  on public.areas_responsables (lower(trim(area)), lower(trim(coalesce(subarea, ''))));

alter table public.areas_responsables enable row level security;

-- Lectura: cualquier usuario autenticado (los formularios necesitan la lista).
drop policy if exists areas_responsables_select_authenticated on public.areas_responsables;
create policy areas_responsables_select_authenticated
  on public.areas_responsables for select to authenticated
  using (true);

-- Escritura: solo mediante las funciones de abajo (no hay políticas de insert/update/delete).
revoke all on table public.areas_responsables from public, anon;
revoke insert, update, delete, truncate on table public.areas_responsables from authenticated;
grant select on table public.areas_responsables to authenticated;

-- Quién puede modificar jefaturas: perfiles activos con rol DireccionGeneral o Administrador
-- (los mismos que tienen permiso de edición en la aplicación).
create or replace function public.puede_gestionar_areas()
returns boolean
language sql
stable
security definer
set search_path to ''
as $$
  select auth.uid() is not null
    and exists (
      select 1
      from public.perfiles
      where id = auth.uid()
        and activo = true
        and rol in ('DireccionGeneral', 'Administrador')
    );
$$;

revoke all on function public.puede_gestionar_areas() from public, anon;
grant execute on function public.puede_gestionar_areas() to authenticated;

-- Crea (p_id null) o modifica (p_id con valor) un área o subárea.
create or replace function public.guardar_area_responsable(
  p_id bigint,
  p_area text,
  p_subarea text,
  p_responsable text
)
returns public.areas_responsables
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_area text := nullif(regexp_replace(trim(coalesce(p_area, '')), '\s+', ' ', 'g'), '');
  v_subarea text := nullif(regexp_replace(trim(coalesce(p_subarea, '')), '\s+', ' ', 'g'), '');
  v_responsable text := nullif(regexp_replace(trim(coalesce(p_responsable, '')), '\s+', ' ', 'g'), '');
  v_actual public.areas_responsables;
  v_result public.areas_responsables;
begin
  if not public.puede_gestionar_areas() then
    raise exception 'No tiene permisos para modificar las jefaturas' using errcode = '42501';
  end if;

  if v_area is null or v_responsable is null then
    raise exception 'El área y el responsable son obligatorios';
  end if;
  if length(v_area) not between 2 and 120
     or (v_subarea is not null and length(v_subarea) not between 2 and 120) then
    raise exception 'El nombre del área debe tener entre 2 y 120 caracteres';
  end if;
  if length(v_responsable) not between 2 and 160 then
    raise exception 'El nombre del responsable debe tener entre 2 y 160 caracteres';
  end if;

  if p_id is null then
    if v_subarea is not null and not exists (
      select 1 from public.areas_responsables
      where subarea is null and lower(trim(area)) = lower(v_area)
    ) then
      raise exception 'La subárea debe pertenecer a un área que ya existe';
    end if;

    insert into public.areas_responsables (area, subarea, responsable, actualizado_por)
    values (v_area, v_subarea, v_responsable, auth.uid())
    returning * into v_result;

    return v_result;
  end if;

  select * into v_actual
  from public.areas_responsables
  where id = p_id
  for update;

  if not found then
    raise exception 'El registro que intenta modificar ya no existe';
  end if;

  if (v_actual.subarea is null) <> (v_subarea is null) then
    raise exception 'No se puede convertir un área en subárea ni una subárea en área';
  end if;

  if v_actual.subarea is not null and lower(v_area) <> lower(trim(v_actual.area)) then
    raise exception 'Para mover una subárea a otra área, elimínela y créela de nuevo';
  end if;

  update public.areas_responsables
  set area = case when v_actual.subarea is null then v_area else area end,
      subarea = v_subarea,
      responsable = v_responsable,
      actualizado_en = now(),
      actualizado_por = auth.uid()
  where id = p_id
  returning * into v_result;

  -- Si se renombró un área principal, sus subáreas se mudan al nombre nuevo.
  if v_actual.subarea is null and v_area <> v_actual.area then
    update public.areas_responsables
    set area = v_area,
        actualizado_en = now(),
        actualizado_por = auth.uid()
    where subarea is not null
      and lower(trim(area)) = lower(trim(v_actual.area));
  end if;

  return v_result;
exception
  when unique_violation then
    raise exception 'Ya existe un área o subárea con ese nombre';
end;
$$;

revoke all on function public.guardar_area_responsable(bigint, text, text, text) from public, anon;
grant execute on function public.guardar_area_responsable(bigint, text, text, text) to authenticated;

-- Elimina un área o una subárea. Un área con subáreas no se puede eliminar hasta quitar estas.
create or replace function public.eliminar_area_responsable(p_id bigint)
returns void
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_actual public.areas_responsables;
begin
  if not public.puede_gestionar_areas() then
    raise exception 'No tiene permisos para modificar las jefaturas' using errcode = '42501';
  end if;

  select * into v_actual
  from public.areas_responsables
  where id = p_id
  for update;

  if not found then
    raise exception 'El registro que intenta eliminar ya no existe';
  end if;

  if v_actual.subarea is null and exists (
    select 1 from public.areas_responsables
    where subarea is not null and lower(trim(area)) = lower(trim(v_actual.area))
  ) then
    raise exception 'Primero elimine las subáreas de esta área';
  end if;

  delete from public.areas_responsables where id = p_id;
end;
$$;

revoke all on function public.eliminar_area_responsable(bigint) from public, anon;
grant execute on function public.eliminar_area_responsable(bigint) to authenticated;

